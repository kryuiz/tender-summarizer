import json

import httpx
from pydantic import ValidationError

from app.schemas import TenderSummary


OLLAMA_URL = "http://127.0.0.1:11434/api/generate"
MODEL = "llama3.1:8b"


async def summarize_text(text: str) -> TenderSummary:
    prompt = f"""
Ты анализируешь тендерную документацию.

Твоя задача — извлечь ТОЛЬКО информацию,
которая явно присутствует в документе.

КРИТИЧЕСКИ ВАЖНО:
- Никогда не придумывай значения.
- Не объединяй несколько чисел из разных мест документа.
- Не делай арифметические вычисления.
- Не делай выводы, которых прямо нет в документе.
- Если не уверен, что информация относится к нужному полю,
  используй значение по умолчанию.

ПОЛЯ:

1. contract_amount

Найди именно цену/начальную максимальную цену контракта.
Верни точное значение, указанное в документе.

НЕ используй:
- номера закупки;
- ИКЗ;
- номера документов;
- ОКПД;
- КБК;
- банковские реквизиты;
- любые другие длинные числовые последовательности.

Если цена контракта явно не указана:
"Не указано".

2. deadline

Найди именно срок исполнения обязательств поставщика
или срок поставки товара.

Не используй сроки:
- оплаты;
- приемки документов;
- предоставления документов;
- уведомления;
- исправления ошибок;
- других административных действий.

Если срок поставки/исполнения не указан:
"Не указано".

3. requirements

Верни конкретные обязательные требования к поставщику
или товару.

Не пересказывай их своими словами.
Используй информацию из документа.

Если требований нет:
[].

4. penalties

Верни ТОЛЬКО конкретные штрафы, пени и неустойки,
если они явно указаны в документе.

Например:
- размер штрафа;
- процент;
- фиксированная сумма;
- формула расчёта пени;
- размер пени за день просрочки.

НЕ превращай условия, при которых возникает ответственность,
в сами штрафы.

Если конкретный размер штрафа/пени/неустойки
не указан:
[].

Отвечай только JSON согласно предоставленной схеме.

Документ:

{text}
"""
   
    schema = TenderSummary.model_json_schema()

    async with httpx.AsyncClient() as client:
        response = await client.post(
            OLLAMA_URL,
            json={
                "model": MODEL,
                "prompt": prompt,
                "stream": False,
                "format": schema,
            },
            timeout=120,
        )

    response.raise_for_status()

    data = json.loads(response.json()["response"])

    try:
        return TenderSummary.model_validate(data)
    except ValidationError as e:
        raise ValueError("LLM returned invalid response") from e
